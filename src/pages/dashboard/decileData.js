/**
 * Look up the real Population and Decile for a given combination of segment labels.
 * Labels must match the strings used in decileData.js exactly.
 * Returns { population: number, decile: string } — population is 0 and decile is ''
 * if no matching row exists.
 */
export function getDecileInfo(rfm, loyalty, behaviour, lifecycle) {
    const row = parsedDecileData.find(
        r => r.RFM === rfm && r.Loyalty === loyalty && r.Behaviour === behaviour && r.Lifecycle === lifecycle
    );
    return row ? { population: row.Population, decile: row.Decile } : { population: 0, decile: '' };
}
